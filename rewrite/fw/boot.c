/* Пара записей счётчика MAC (лог-строка vendor «MAIN() Configurre MAC counters»; REGS-KNOWN
 * mac_cnt_sel_* / mac_cnt_cfg_*). Поле cfg — значение настройки (старшее полуслово 0x4…0x6c,
 * шаг ячейки/флаги), а не адрес: 0x880000, 0x840000 и т. п. ниже — числа, совпадающие с
 * адресами по виду, к памяти не обращаются. */
struct mac_cnt_ent {
    u32 sel;                                   /* → регистр sel: номер события */
    u32 cfg;                                   /* → регистр cfg: настройка (не адрес) */
};

