#ifndef ABFT_CFG_H
#define ABFT_CFG_H
/* Конфигурация A-BFT нашего AP/PCP (open): фиксированная, без адаптации (802.11-2020 10.42.5).
 *
 * A-BFT в каждом BI: поле N BIs A-BFT = 1 («set to 1 if every beacon interval contains an A-BFT», 9.3.4.2), тогда
 * Next A-BFT всегда 0 (uc: bcn_bi.abft_bi_left перезагружается n_bi_abft − 1 = 0). vendor 6.2 ставил 4 — A-BFT раз в
 * 4 BI, а станция без ассоциации ждёт до 3 BI (300 мс при BI 100 мс) до попытки.
 *
 * Число слотов L = A-BFT Length + 1. k станций, одновременно отвечающих в одном A-BFT, выбирают слот равновероятно
 * (10.42.5.2); вероятность, что данная станция одна в своём слоте, p = (1 − 1/L)^(k−1):
 *     L = 1: k = 2 — 0;    L = 2: k = 2 — 0,50, k = 3 — 0,25;   L = 4: 0,75 / 0,56;   L = 8: 0,875 / 0,77.
 * При L ≥ 2 станция без Feedback может повторить RSS в том же A-BFT со случайной задержкой в [0, L) слотов (10.42.5.2),
 * при L = 1 два одновременных ответчика не разойдутся никогда. Эфир A-BFT в каждом BI = MBIFS + L·aSSSlotTime(FSS),
 * aSSSlotTime при FSS 15 (16 SSW) = 289,9 мкс: L = 1 — 0,3 мс (0,3 % BI 100 мс), L = 2 — 0,59 мс, L = 4 — 1,17 мс,
 * L = 8 — 2,33 мс. Обычно входит одна станция (k = 1, хватает любого L); L = 2 разводит две одновременные за 2 BI в
 * среднем (1/p), ценой 0,59 % эфира. Больше слотов — постоянная плата эфиром каждый BI за редкое событие. Хост может
 * задать другое L в WMI_PCP_START (abft_len 1…8); 0 и прочее — значение по умолчанию.
 *
 * FSS 15 — 16 SSW в слоте (максимум поля): станция с 64 секторами проходит RSS за 4 A-BFT (фрагментами), с 16 — за
 * один; меньший FSS короче слот (FSS 4 — 5 SSW, 114,9 мкс), но станции с многими секторами учатся дольше. Минимум
 * поля — aSSFramesPerSlot = 4 (Table 11-22): его ставит long range. */
#define ABFT_N_BI_ABFT           1u     /* A-BFT в каждом BI (поле N BIs A-BFT; Next A-BFT = 0) */
#define ABFT_LEN_SLOTS_DEFAULT   2u     /* слотов A-BFT по умолчанию (поле A-BFT Length = 1) */
#define ABFT_FSS_FIELD           15u    /* поле FSS: 16 SSW в слоте */
#define ABFT_FSS_FIELD_MIN       4u     /* aSSFramesPerSlot — минимум поля (long range) */
#endif
