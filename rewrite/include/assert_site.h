/* Фатальный ассерт fw с точным местом.
 *
 * fw_sysassert_fatal отдаёт хосту адрес своего вызова (site, blink): коды ассертов повторяются в разных
 * местах, и только site однозначно указывает проверку (addr2line по fw.elf). Вызов в хвостовой позиции
 * gcc превращает в переход (sibcall) — тогда blink указывает уже на вызывающего объемлющей функции, место
 * теряется (2026-10-27: 58 таких вызовов). Пустой asm после вызова выводит его из хвостовой позиции.
 * Подключается ко всем исходникам fw/ через -include (Makefile); определение — (fw_sysassert_fatal) в
 * скобках, чтобы макрос не раскрывался. Код после вызова сохраняется: ассерт может вернуться (повторный
 * ассерт, отладчик).
 * uc этот приём не применяет: барьер меняет раскладку блоков в горячих функциях uc (ХРУПКО) — у uc_assert
 * в хвостовой позиции (15 мест) место = адрес возврата объемлющей функции, код — в журнале uc. */
#ifndef ASSERT_SITE_H
#define ASSERT_SITE_H

#define fw_sysassert_fatal(caller, code) \
    do { (fw_sysassert_fatal)((caller), (code)); __asm__ volatile(""); } while (0)

#endif
