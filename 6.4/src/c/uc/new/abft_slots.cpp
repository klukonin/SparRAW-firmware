/* Число слотов A-BFT для ответчика (6.4; 802.11-2020 9.3.4.2, 10.42.5.2).
 *
 * Поле A-BFT Length в BI Control — «число слотов минус 1» (9.3.4.2), а
 * 10.42.5.2 берёт счётчик отсрочки из [0, A-BFT Length), называя так же
 * значение поля.  Буквально это никогда не выбирает последний слот, а при
 * поле 0 (один слот) диапазон пуст.  Принято чтение «A-BFT Length = число
 * слотов», как в 4.1 (поле + 1).  В 6.2 +1 потеряно: при двух слотах
 * станция всегда отвечала в первом.
 *
 * abft_responder__respond_flow (первый выбор и повтор после неудачи)
 * извлекает поле командой bmsk r14,rX,2; патч 0008 заменяет её вызовом
 * вставки ниже.  Вставки меняют только r14 и флаги не трогают.
 */
__asm__(
	"	.section .text.abft_slot_count,\"ax\",@progbits\n"
	"	.p2align 2\n"
	"	.global abft__slot_count_r3\n"
	"abft__slot_count_r3:\n"          /* r14 = ((r3 >> 0) & 7) + 1 */
	"	bmsk r14,r3,0x2\n"
	"	j.d [blink]\n"
	"	add r14,r14,0x1\n"
	"	.global abft__slot_count_r11\n"
	"abft__slot_count_r11:\n"
	"	bmsk r14,r11,0x2\n"
	"	j.d [blink]\n"
	"	add r14,r14,0x1\n");
