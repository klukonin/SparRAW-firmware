/* set_tsf_event — измерительный вариант: тот же взвод компаратора TSF плюс
 * запись в журнал того, что происходит с регистром событий r42.
 *
 * Зачем: развёртка маяка взводит аппаратный компаратор (0x886d30/34/38) и
 * тут же идёт передавать маяк, не дожидаясь события. Чтобы заставить её
 * ждать, нужно знать, КАКОЙ бит r42 взводит компаратор. Известные биты
 * событий: 4, 7, 9, 12, 14, 16, 18, 19; первый
 * кандидат — 9, потому что uc_sleep_until_event добавляет его к маске
 * всегда.
 *
 * Поведение по отношению к прошивке не меняется: взвод тот же, добавлены
 * только записи в кольцо журнала и ограниченный опрос. Ждать здесь пока
 * НЕЛЬЗЯ — если ошибиться битом, развёртка встанет намертво.
 */
#include "uc.h"

/* Дождаться события компаратора прямо здесь. Это и есть искомая
 * модификация: развёртка маяка — единственный вызывающий set_tsf_event,
 * поэтому ожидание, вложенное сюда, задерживает выход маяка ровно на
 * посчитанную случайную задержку.
 *
 * Бит события выбран измерением: r42 на входе в set_tsf_event принимает
 * два значения, 0x00f2c3bf и 0x00f2c1bf, различающиеся ровно битом 9 —
 * и ровно этот бит примитив ожидания всегда добавляет к маске
 * пробуждения (bset r13,r13,0x9 в 0x9318b8).
 *
 * Меняет поведение прошивки; откат — передёргивание питания. */
#ifndef WAIT_FOR_TSF
#define WAIT_FOR_TSF 0
#endif

/* (Привязка базы переехала в bi::decide_beacon_kind — читать время отсюда
 * нельзя.) Ниже оставлено описание самого механизма.
 *
 * Привязать базу к текущему времени.
 *
 * Развёртка ведёт цель не от «сейчас», а от накопителя по 0x801450:
 * каждый раз прибавляет к нему uniform_random << 10, то есть в среднем
 * ровно BI (среднее случайного ≈ 100, 100 * 1024 = 102 400 мкс). Замысел
 * верный — маяк планируется через интервал плюс-минус случайное, — но
 * накопитель ни с чем не сверяется и уходит: измерено отставание около
 * 18 BI. Здесь мы оставляем случайную часть, а базу берём от реального
 * TSF, и результат пишем обратно в накопитель, так что поправка держится.
 *
 * Меняет поведение прошивки; откат — передёргивание питания. */
#ifndef RESYNC_TSF_BASE
#define RESYNC_TSF_BASE 0
#endif

struct tsf64 {
	u32 lo;
	u32 hi;
};

enum {
	UCLOG_MOD_SYSTEM = 0,
	UCLOG_LVL_INFO   = 2,
	MSG_SET_TSF_EVENT = 0xa2000d8c,  /* "set_tsf_event()" */
	MSG_MASK          = 0xa600188c,  /* "[NNL] non_idle_mask: 0x%x", один аргумент */
	MAC_CMD_TSF_ARM   = 0x02000040,
	SPIN_LIMIT        = 256,         /* опрос ограничен: развёртка не должна встать */
	TSF_SPIN_GUARD    = 60000,       /* с запасом на 1980 мкс задержки */
	BI_USEC           = 102400,      /* интервал маяка, 100 TU */
	MIN_AHEAD_USEC    = 200,         /* чтобы компаратору было что ждать */
};

extern "C" void uc_sleep_until_event(u32 mask, u32 aux);
extern "C" u32 uc_read_tsf_lo(void);
extern "C" void uc_read_tsf64(struct tsf64 *out);

extern "C" void set_tsf_event(const struct tsf64 *when)
{
	bool log = uclog_enabled(UCLOG_MOD_SYSTEM, UCLOG_LVL_INFO);

	/* Читаем регистр событий ДО взвода. Между двумя вызовами проходит BI,
	 * и компаратор, заряженный в прошлый раз, за это время срабатывает —
	 * значит его бит должен быть виден именно здесь, а не после взвода,
	 * который его, скорее всего, и сбрасывает. */
	u32 at_entry = uc_events();

	if (log) {
		uclog(MSG_SET_TSF_EVENT);
		uclog1(MSG_MASK, at_entry);
	}

	mac_cmd(MAC_CMD_TSF_ARM);

	TSF_CMP_LO = when->lo;
	TSF_CMP_HI = when->hi;
	TSF_CMP_CTL = TSF_CMP_ARM;

	if (!log)
		return;

	/* Ждём не события, а самого TSF: uc_sleep_until_event требует знать
	 * бит пробуждения, а он не найден — с маской 1<<9 ucode засыпает
	 * навсегда (проверено: счётчик BTI замирает). Опрос по TSF от этого
	 * знания не зависит и всегда завершается: сторож ограничивает его
	 * сверху, разница считается знаковой, поэтому перенос через ноль
	 * обрабатывается сам. */
	if (WAIT_FOR_TSF) {
		for (u32 g = 0; g < TSF_SPIN_GUARD; g++)
			if ((int)(uc_read_tsf_lo() - when->lo) >= 0)
				break;
	}

	/* и сразу после взвода: разница с at_entry и покажет, какой бит
	 * компаратор взводит, а какой взвод сбрасывает */
	u32 after = uc_events();
	uclog1(MSG_MASK, after);
	uclog1(MSG_MASK, at_entry ^ after);
}
