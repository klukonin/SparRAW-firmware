def _check_no_dup():
    """Питон-литерал молча съедает повторный ключ — ловим это по исходнику."""
    import re as _re
    src = open(__file__, encoding='utf-8').read()
    keys = _re.findall(r'^\s+(0x[0-9a-f]{2}): \(', src, _re.M)
    dup = {k for k in keys if keys.count(k) > 1}
    if dup:
        raise SystemExit('дубликаты ключей в SENSE: %s' % ', '.join(sorted(dup)))


def main():
    _check_no_dup()
    spec = importlib.util.spec_from_file_location(
        'm', '../../SparRAW-tools/host/wil_mac_ring.py')
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)

    by = collections.defaultdict(collections.Counter)
    for l in open('ref/MAC-CMD-SITES.txt'):
        if not l.startswith('0x'):
            continue
        p = l.split()
        mm = re.match(r'0x([0-9a-f]{2})', p[2])
        if mm:
            # бит 31 — метка PMC, а не часть кода (см. пак Talyn)
            by[int(mm.group(1), 16) & 0x7f][p[-1]] += 1

    obs = collections.defaultdict(collections.Counter)
    for f in sys.argv[1:]:
        b = open(f, 'rb').read()
        sn = [list(struct.unpack('<256I', b[i * 1024:(i + 1) * 1024]))
              for i in range(len(b) // 1024)]
        prev = sn[0]
        for cur in sn[1:]:
            w = m.window(prev, cur)
            if w and w[2]:
                for j in range(w[1]):
                    i = (w[0] + j) % 256
                    if prev[i] == cur[i]:
                        continue        # старое слово, не команда
                    v = cur[i]
                    obs[(v >> 24) & 0x7f][v & 0xffffff] += 1
            prev = cur

    codes = set(by) | set(obs)
    total = len(codes)
    lv = collections.Counter(SENSE[c][0] for c in codes if c in SENSE)
    unused = sorted(set(SENSE) - codes)
    print('# Карта команд MAC. Всего кодов: %d' % total)
    print('# Обоснование: железо %d, разбор кода %d, единственное место %d, '
          'единственный блок %d, профиль %d, СЛАБО %d, нет %d'
          % (lv['железо'], lv['код'], lv['место'], lv['блок'], lv['профиль'],
             lv['слабо'], total - sum(lv.values())))
    if unused:
        print('# в словаре есть записи для кодов, которых нет в карте: %s'
              % ', '.join('0x%02x' % c for c in unused))
    print('# %-4s %7s %5s  %-30s %s' % ('код', 'набл.', 'мест', 'частые параметры',
                                        'смысл / главный отправитель'))
    for c in sorted(set(by) | set(obs)):
        n = sum(obs[c].values())
        pars = ', '.join('0x%06x' % p for p, _ in obs[c].most_common(3))
        top = ', '.join(k for k, _ in by[c].most_common(2)) or '— места нет'
        e = SENSE.get(c)
        txt = ('[%s] %s' % e) if e else top
        print('0x%02x  %7d %5d  %-30s %s'
              % (c, n, sum(by[c].values()), pars, txt))


if __name__ == '__main__':
    main()
